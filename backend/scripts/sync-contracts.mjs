// Copies the TypeChain bindings for the platform contracts from the contracts
// workspace into src/blockchain/generated. Run after any contract change:
//   npm run contracts:sync
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const backend = join(dirname(fileURLToPath(import.meta.url)), '..');
const source = join(backend, '..', 'contracts', 'types', 'ethers-contracts');
const target = join(backend, 'src', 'blockchain', 'generated');

/** The deployed platform contracts: [folder, name]. */
const CONTRACTS = [
  ['access', 'AccessRegistry'],
  ['projects', 'ProjectLedger'],
  ['inputs', 'VoucherRegistry'],
  ['field', 'FieldRecordLog'],
  ['warehouse', 'WarehouseReceipt'],
  ['trade', 'TradeLedger'],
  ['insurance', 'InsuranceRegistry'],
  ['settlement', 'SettlementLedger'],
  ['consent', 'ConsentRegistry'],
];

if (!existsSync(source)) {
  console.error(`No bindings at ${source}. Run "npx hardhat build" in contracts/ first.`);
  process.exit(1);
}

rmSync(target, { recursive: true, force: true });
const copy = (rel) => {
  const from = join(source, rel);
  if (!existsSync(from)) throw new Error(`Missing generated file: ${rel}`);
  mkdirSync(dirname(join(target, rel)), { recursive: true });
  cpSync(from, join(target, rel));
};

copy('common.ts');
for (const [dir, name] of CONTRACTS) {
  copy(`${dir}/${name}.ts`);
  const factory = `factories/${dir}/${name}__factory.ts`;
  copy(factory);
  // The backend only connects to deployed contracts, never deploys them:
  // drop the bytecode and keep the ABI.
  const file = join(target, factory);
  const stripped = readFileSync(file, 'utf8').replace(/const _bytecode =\s*"0x[0-9a-fA-F]*";/, 'const _bytecode = "0x";');
  if (!stripped.includes('const _bytecode = "0x";')) throw new Error(`Could not strip bytecode from ${factory}`);
  writeFileSync(file, stripped);
}

const header = '/* Autogenerated by scripts/sync-contracts.mjs. Do not edit. */\n';
writeFileSync(
  join(target, 'index.ts'),
  header +
    CONTRACTS.map(
      ([dir, name]) =>
        `export type { ${name} } from './${dir}/${name}.js';\n` +
        `export { ${name}__factory } from './factories/${dir}/${name}__factory.js';\n`,
    ).join(''),
);
console.log(`Synced ${CONTRACTS.length} contract bindings into src/blockchain/generated`);
