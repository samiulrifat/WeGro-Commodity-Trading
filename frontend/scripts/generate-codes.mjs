// Writes the backend's code lists (published in its OpenAPI document) as
// lists and types, so the app's wording can be checked to cover every one. Part of
// `npm run api:generate`; reads the same document as the API client.
import { writeFileSync } from 'node:fs';

const url = process.env.OPENAPI_URL || 'http://localhost:3000/docs-json';
const LISTS = {
  ErrorCode: 'Why the backend refused a request (error code).',
  LedgerErrorCode: 'Why the ledger itself refused (contract error name).',
  ValidationRule: 'What an input check found wrong with a field.',
  District: 'The 64 districts, by the code the API uses (BOGURA).',
  IdCheckReason: 'Why an ID check rule passed, warned or failed.',
};

const doc = await (await fetch(url)).json();
const constName = (name) =>
  name.replace(/([a-z])([A-Z])/g, '$1_$2').toUpperCase() + 'S';

let out =
  '// Generated by `npm run api:generate` from the backend. Do not edit.\n';
for (const [name, about] of Object.entries(LISTS)) {
  const values = doc.components?.schemas?.[name]?.enum;
  if (!Array.isArray(values) || values.length === 0) {
    throw new Error(`${url} does not publish ${name}`);
  }
  out += `\n/** ${about} */\nexport const ${constName(name)} = ${JSON.stringify(values)} as const;\n`;
  out += `export type ${name} = (typeof ${constName(name)})[number];\n`;
}
writeFileSync(new URL('../src/api/generated/codes.ts', import.meta.url), out);
